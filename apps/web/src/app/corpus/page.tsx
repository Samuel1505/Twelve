import type { Metadata } from "next";
import type { ReactNode } from "react";
import { CaseDiff } from "@/components/corpus/case-diff";
import { PageHeader } from "@/components/site/page-header";
import { CodeBlock } from "@/components/ui/code-block";
import { Pill } from "@/components/ui/unit-chip";
import { type Case, cases, metrics } from "@/lib/corpus";
import { ruleTitle } from "@/lib/rules";
import { cn } from "@/lib/cn";

export const metadata: Metadata = { title: "Corpus · Twelve" };

/** `code` spans from the spec's markdown, rendered as mono. */
function md(s: string): ReactNode {
  return s.split(/(`[^`]+`)/).map((p, i) =>
    p.startsWith("`") ? <code key={i} className="num rounded bg-elev-2 px-1 py-px text-[12px] text-fg">{p.slice(1, -1)}</code> : p);
}

export default function CorpusPage() {
  const m = metrics();
  const all = cases();
  const highFound = m.source.highRecall[0] + m.deployed.highRecall[0];
  const highTotal = m.source.highRecall[1] + m.deployed.highRecall[1];
  const rules = Object.entries(m.source.rules).sort(([a], [b]) => a.localeCompare(b));

  return (
    <div className="mx-auto max-w-[1120px] px-5 pb-24 pt-12 sm:px-8 sm:pt-16">
      <PageHeader
        eyebrow="Analyzer · measured"
        title="Corpus"
        lead={<>Every rule is held to a set of planted bugs, each with a fixed twin that must stay clean, plus contracts that
          look risky but are correct. A rule that fires on safe code is worse than no rule, so any change that adds a false
          alarm or misses a high-severity bug fails CI.</>}
      />

      <dl className="mt-14 grid gap-px overflow-hidden rounded-2xl border border-line bg-line sm:grid-cols-3">
        <Stat v={`${highFound} / ${highTotal}`} k="high-severity bugs caught" d={`${m.source.highRecall[0]} from source, ${m.deployed.highRecall[0]} deployed on Arc testnet`} />
        <Stat v={String(m.source.highSafeFp + m.deployed.highSafeFp)} k="high-severity alarms on safe code" d="fixed twins and hard negatives" />
        <Stat v={String(m.source.cases + m.deployed.cases)} k="cases" d={`${m.source.cases} source, ${m.deployed.cases} deployed`} />
      </dl>

      <section className="mt-20">
        <h2 className="text-[22px] font-semibold tracking-[-0.02em] text-fg">By rule</h2>
        <p className="mt-2 max-w-[62ch] text-[14px] leading-relaxed text-muted">Source mode, every severity. Generated by <span className="num text-fg">twelve.metrics</span> and committed with each analyzer change.</p>
        <div className="mt-6 overflow-x-auto rounded-2xl border border-line">
          <table className="w-full min-w-[560px] text-left text-[13px]">
            <thead className="border-b border-line text-[12px] text-subtle">
              <tr>
                <th className="px-5 py-3 font-normal">Rule</th>
                <th className="px-3 py-3 text-right font-normal">Planted</th>
                <th className="px-3 py-3 text-right font-normal">Caught</th>
                <th className="px-5 py-3 text-right font-normal">On safe code</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-line">
              {rules.map(([id, r]) => (
                <tr key={id}>
                  <td className="px-5 py-3"><span className="num text-fg">{id}</span> <span className="ml-2 text-muted">{ruleTitle(id)}</span></td>
                  <td className="num px-3 py-3 text-right text-muted">{r.expected}</td>
                  <td className={cn("num px-3 py-3 text-right", r.matched === r.expected ? "text-fg" : "text-bad")}>{r.matched}</td>
                  <td className={cn("num px-5 py-3 text-right", r.safeFp === 0 ? "text-ok" : "text-bad")}>{r.safeFp}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </section>

      <section className="mt-20">
        <h2 className="text-[22px] font-semibold tracking-[-0.02em] text-fg">Cases</h2>
        <p className="mt-2 max-w-[62ch] text-[14px] leading-relaxed text-muted">
          Open a case to see the planted bug against its fix. The flagged line is underlined where the analyzer must report it.
        </p>
        <div className="mt-6 divide-y divide-line overflow-hidden rounded-2xl border border-line bg-elev">
          {all.map((c, i) => <CaseRow key={c.id} c={c} open={i === 0} />)}
        </div>
      </section>
    </div>
  );
}

function Stat({ v, k, d }: { v: string; k: string; d: string }) {
  return (
    <div className="bg-bg px-6 py-6">
      <dt className="sr-only">{k}</dt>
      <dd>
        <div className="num text-[32px] leading-none tracking-[-0.02em] text-fg">{v}</div>
        <div className="mt-3 text-[14px] text-fg">{k}</div>
        <div className="mt-1 text-[12.5px] text-subtle">{d}</div>
      </dd>
    </div>
  );
}

function CaseRow({ c, open }: { c: Case; open: boolean }) {
  const rules = [...new Set(c.expect.map((e) => e.rule))];
  return (
    <details className="group" open={open}>
      <summary className="flex cursor-pointer list-none items-start gap-4 px-5 py-4 hover:bg-elev-2/50 [&::-webkit-details-marker]:hidden">
        <svg aria-hidden viewBox="0 0 16 16" className="mt-1 size-3 shrink-0 text-subtle transition-transform duration-150 ease-out group-open:rotate-90" fill="currentColor">
          <path d="M6 3.5l5 4.5-5 4.5z" />
        </svg>
        <span className="num w-8 shrink-0 text-[13px] text-subtle">{c.id}</span>
        <span className="min-w-0 flex-1">
          <span className="block text-[14px] text-fg">{c.name}</span>
          {c.pattern && <span className="mt-1 block text-[13px] leading-relaxed text-muted">{md(c.pattern)}</span>}
        </span>
        <span className="flex shrink-0 flex-wrap justify-end gap-1.5">
          {rules.length ? rules.map((r) => {
            const sev = c.expect.find((e) => e.rule === r)!.severity;
            return <Pill key={r} tone={sev === "HIGH" ? "HIGH" : sev === "MEDIUM" ? "MEDIUM" : "INFO"}>{r}</Pill>;
          }) : <Pill tone="CLEAN">must stay clean</Pill>}
        </span>
      </summary>
      <div className="border-t border-line bg-sunken">
        {c.kind === "pair"
          ? <CaseDiff hunks={c.hunks} expectLines={c.expect.map((e) => e.line)} />
          : <CodeBlock code={c.source ?? ""} copy={false} className="rounded-none border-0" title={c.kind === "negative" ? "safe.sol" : "bug.sol"} />}
      </div>
    </details>
  );
}
