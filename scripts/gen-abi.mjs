// Generates packages/shared/src/abi.ts from forge artifacts (ARCHITECTURE §2.7). Run after `forge build`.
import { readFileSync, writeFileSync } from "node:fs";

const read = (name) =>
  JSON.parse(readFileSync(new URL(`../contracts/out/${name}.sol/${name}.json`, import.meta.url))).abi;
const out = `// GENERATED by scripts/gen-abi.mjs from contracts/out — do not edit.
export const twelveRegistryAbi = ${JSON.stringify(read("TwelveRegistry"), null, 2)} as const;

export const twelveGateAbi = ${JSON.stringify(read("TwelveGate"), null, 2)} as const;
`;
writeFileSync(new URL("../packages/shared/src/abi.ts", import.meta.url), out);
console.log("wrote packages/shared/src/abi.ts");
